# lower(), converts characters into lowercase
a = 'Hello World Python'
b = 'I Am Testing You'
print('lower: ',a.lower())

# upper(), converts character into uppercase
print('upper: ' ,a.upper())

# title(), converts string to title case
print( 'title: ',a.title())

# isupper()
print( 'isupper? ',a.isupper())

# islower()
print( 'islower? ',a.islower())

# istitle()
print( 'istitle? ',b.istitle())
